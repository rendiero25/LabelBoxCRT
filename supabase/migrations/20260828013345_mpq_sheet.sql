-- MPQ Sheet: standar jumlah sheet maksimum dalam satu box, per ukuran.
--
-- Isinya datang dari dokumen "List MPQ CRT" (update 27 September 2021) dan
-- dipakai sebagai rujukan, bukan sebagai data yang tumbuh sendiri di aplikasi.
-- Karena itu tidak ada satu pun RPC tulis di sini: tabelnya hanya bisa dibaca,
-- dan revisi dokumen berikutnya masuk sebagai migrasi baru -- sama seperti
-- dokumennya sendiri yang diganti utuh, bukan disunting baris per baris.
--
-- Ukuran disimpan dua kali. product_size adalah ejaan seperti di dokumen, dan
-- itulah yang dibaca admin. product_size_key adalah ejaan yang sama tanpa
-- spasi, dan hanya itu yang dipakai membandingkan: dokumen kadang menulis
-- "L=55 MM" sementara label menulis "L=55MM" -- persis alasan yang sama dengan
-- 20260827103000_match_schedule_ignoring_spaces.

create table public.mpq_sheet_rows (
  id uuid primary key default gen_random_uuid(),
  -- Nomor urut dokumen setelah baris kembar dibuang. Disimpan supaya urutan
  -- asli tetap bisa dipulihkan meski tabel di layar sedang diurutkan menurut
  -- kolom lain.
  row_no integer not null unique check (row_no > 0),
  product_size text not null check (btrim(product_size) <> ''),
  product_size_key text not null
    generated always as (upper(regexp_replace(product_size, '\s', '', 'g'))) stored,
  mpq_qty integer not null check (mpq_qty > 0),
  -- Satuannya ikut disimpan, bukan diasumsikan "PCS/BOX": dokumen memuat
  -- PCS/LAKBAN juga, dan angka MPQ tidak berarti apa-apa tanpa satuannya.
  unit text not null check (btrim(unit) <> ''),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Satu ukuran satu MPQ. Dokumennya memuat 651 baris tetapi 18 di antaranya
  -- mengulang ukuran yang sama dengan MPQ yang sama; yang masuk 633 baris unik.
  constraint mpq_sheet_rows_size_key unique (product_size_key)
);

create trigger mpq_sheet_rows_set_updated_at
before update on public.mpq_sheet_rows
for each row execute function private.set_updated_at();

alter table public.mpq_sheet_rows enable row level security;
alter table public.mpq_sheet_rows force row level security;

